import { test, expect } from '@playwright/test';
import { createSampleData } from '../../src/lib/demoSamples.js';
import { PART3_NOW, openPart3, readPart3Envelope, readPart3Bytes } from '../helpers/part3.js';
import { button, link, nav, commit, enterEditor, addComponent, coordinates, fillActivity } from '../helpers/shellActions.js';

for (const mode of ['desktop', 'touch']) {
test.describe(mode, () => {
  if (mode === 'touch') test.use({ isMobile: true, hasTouch: true, viewport: { width: 390, height: 844 } });
test('new facility connects editor, reports, activities and stable map focus', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await openPart3(page);
  await enterEditor(page);
  const object = await addComponent(page, 'Community hall', 27, 18);
  expect(object.facilityId).toBeTruthy();
  await button(page, 'Move').click(); await coordinates(page, 28, 18);
  const moved = await commit(page, () => button(page, 'Confirm move').click());
  expect(moved.data.layout.find(row => row.objectId === object.objectId)).toEqual({ ...object, x: 28 });
  await button(page, 'Back to workspace').click();
  await link(page, 'Manage activities').click(); await link(page, 'New activity').click();
  await fillActivity(page, 'Hall neighbours morning', object.facilityId);
  const published = await commit(page, () => button(page, 'Publish activity').click());
  const activity = published.data.activities.find(row => row.title === 'Hall neighbours morning');
  expect(activity).toMatchObject({ facility_id: object.facilityId, status: 'published', starts_at: '2026-10-25T01:30:00.000Z', ends_at: '2026-10-25T03:00:00.000Z' });
  await button(page, 'Exit SDP workspace').click();
  await nav(page, 'Activities').click(); await link(page, activity.title).click();
  const joined = await commit(page, () => button(page, 'Join activity').click());
  expect(joined.data.activity_participants.filter(row => row.activity_id === activity.id)).toHaveLength(1);
  await button(page, 'View on map').click();
  await expect(page.locator('.place-button.is-selected')).toContainText('Community hall 2');
  await expect(page.locator('.place-button.is-selected')).toBeFocused();
  await expect(page.locator('.schematic-object.is-selected rect')).toHaveAttribute('x', '560');
  await expect(page.locator('.schematic-object.is-selected rect')).toHaveAttribute('y', '360');
  await page.locator('.place-button.is-selected').click();
  await button(page, 'Report a problem').click();
  await expect(page.getByLabel(/^Facility/)).toHaveValue(object.facilityId);
  await page.getByLabel(/^Description/).fill('The new hall handrail needs a maintenance inspection.');
  const reported = await commit(page, () => button(page, 'Send report').click());
  const report = reported.data.complaints.find(row => row.facility_id === object.facilityId);
  expect(reported.data.complaint_updates.filter(row => row.complaint_id === report.id)).toHaveLength(1);
  await link(page, 'View on map').click();
  await expect(page.locator('.place-button.is-selected')).toContainText('Community hall 2');
  await expect(page.locator('.schematic-object.is-selected rect')).toHaveAttribute('x', '560');
  await expect(page.locator('.schematic-object.is-selected rect')).toHaveAttribute('y', '360');
  await enterEditor(page);
  await page.getByRole('button', { name: /^Community hall 2/ }).click();
  await expect(page.getByText('Removal blocked', { exact: true })).toBeVisible();
  await expect(button(page, 'Remove')).toBeDisabled();
  const beforeReload = await readPart3Bytes(page);
  await page.reload();
  expect(await readPart3Bytes(page)).toBe(beforeReload);
  const final = await readPart3Envelope(page);
  expect(final.data.layout.find(row => row.objectId === object.objectId)).toEqual({ ...object, x: 28 });
  expect(final.data.activities.find(row => row.id === activity.id)).toEqual(activity);
  expect(final.data.complaints.find(row => row.id === report.id)).toEqual(report);
  expect(final.data.activity_participants.filter(row => row.activity_id === activity.id)).toHaveLength(1);
  expect(errors).toEqual([]);
});

test('cross-domain reset preserves unrelated storage and leaves no stale draft', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await openPart3(page, 'profile');
  await page.getByLabel('Display name').fill('Part Three saved resident');
  await commit(page, () => button(page, 'Save changes').click());
  await page.reload();
  await nav(page, 'Reports').click();
  await page.getByLabel(/^Facility/).selectOption('hall-01');
  await page.getByLabel(/^Description/).fill('A disposable report to verify coherent whole-domain reset.');
  await page.getByLabel('Report photo (optional)').setInputFiles({ name: 'reset-fixture.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') });
  await expect(page.getByRole('img', { name: 'Selected report photo' })).toBeVisible();
  const withPhoto = await commit(page, () => button(page, 'Send report').click());
  expect(withPhoto.data.attachments).toHaveLength(1);
  await button(page, 'Enter SDP demo workspace').click();
  await link(page, 'Manage activities').click(); await link(page, 'New activity').click();
  await fillActivity(page, 'Disposable reset morning');
  await commit(page, () => button(page, 'Publish activity').click());
  await button(page, 'Exit SDP workspace').click();
  await nav(page, 'Activities').click(); await link(page, 'Disposable reset morning').click();
  await commit(page, () => button(page, 'Join activity').click());
  await enterEditor(page);
  const tree = await addComponent(page, 'Tree', 27, 18);
  expect(tree.facilityId).toBeNull();
  await button(page, 'Move').click(); await coordinates(page, 28, 18);
  await page.evaluate(() => localStorage.setItem('kobi.part3.unrelated', 'keep'));
  const before = await readPart3Bytes(page);
  await button(page, 'Reset demo').click();
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  expect(await readPart3Bytes(page)).toBe(before);
  await expect(page.getByLabel(/^X tile/)).toHaveValue('28');
  await button(page, 'Reset demo').click();
  await commit(page, () => page.getByRole('dialog').getByRole('button', { name: 'Reset demo', exact: true }).click());
  await expect(page.getByRole('heading', { level: 1 })).toBeFocused();
  await expect(page.locator('.schematic-ghost')).toHaveCount(0);
  await expect(page.locator('.placement-form')).toHaveCount(0);
  expect((await readPart3Envelope(page)).data).toEqual(createSampleData(PART3_NOW));
  expect(await page.evaluate(() => localStorage.getItem('kobi.part3.unrelated'))).toBe('keep');
  await page.reload();
  expect((await readPart3Envelope(page)).data).toEqual(createSampleData(PART3_NOW));
  await expect(button(page, 'Retry storage')).toHaveCount(0);
  expect(await page.evaluate(() => localStorage.getItem('kobi.part3.unrelated'))).toBe('keep');
  expect(errors).toEqual([]);
});
});
}
