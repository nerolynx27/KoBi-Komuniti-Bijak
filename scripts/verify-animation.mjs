import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '@playwright/test';
import { filmScenes } from '../src/dev/storyboard/filmTimeline.mjs';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5182/animation.html');
  await page.evaluate(() => document.fonts.ready);
  await page.getByRole('button', { name: 'Play', exact: true }).waitFor({ state: 'visible' });
  await page.locator('.film-panel .pixel-frame').first().waitFor();
  await page.waitForFunction(() => document.querySelector('.film-logo')?.complete && document.querySelector('.film-logo').naturalWidth === 1460);
  assert.equal(await page.locator('.film-demo, .film-wordmark').count(), 0);
  assert.equal(await page.locator('.film-logo').evaluate(logo => getComputedStyle(logo).width), '180px');
  assert.equal(await page.locator('.film-logo-card').getAttribute('data-frame-tone'), 'panel');
  await mkdir('output/animation-review', { recursive: true });
  let sceneThree;
  for (const [index, scene] of filmScenes.entries()) {
    await page.getByRole('button', { name: String(index + 1).padStart(2, '0'), exact: true }).click();
    await page.locator('.film-seek-label span').getByText(scene.title, { exact: true }).waitFor();
    const opacity = await page.locator(`#film-scene-${index + 1} .film-panel`).evaluate(element => Number(getComputedStyle(element).opacity));
    assert(opacity > .95, `Scene ${index + 1} failed to seek`);
    const hiddenPanels = await page.locator('.film-panel').evaluateAll((panels, active) => panels.every((panel, panelIndex) => panelIndex === active || Number(getComputedStyle(panel).opacity) < .001), index);
    assert(hiddenPanels, `Other scene panels remained visible in scene ${index + 1}`);
    const panelFit = await page.locator(`#film-scene-${index + 1} .film-panel`).evaluate(element => {
      const panel = element.getBoundingClientRect(), canvas = element.closest('.film-canvas').getBoundingClientRect();
      return { top: (panel.top-canvas.top)/canvas.height*720, bottom: (panel.bottom-canvas.top)/canvas.height*720 };
    });
    console.log('Panel', index + 1, panelFit);
    await page.locator('.film-viewport').screenshot({ path: `output/animation-review/scene-${index + 1}.png` });
    if (index === 2) sceneThree = await page.evaluate(() => document.getAnimations().map(animation => { const style = getComputedStyle(animation.effect.target); return [animation.currentTime, style.transform, style.opacity]; }));
    assert(panelFit.top >= 0 && panelFit.bottom <= 620, `Scene ${index + 1} panel exceeds caption area`);
    await page.locator('.film-viewport').screenshot({ path: `output/animation-review/scene-${index + 1}.png` });
  }
  await page.locator('#film-seek').evaluate(input => { input.step = '1'; });
  await page.locator('#film-seek').focus();
  await page.keyboard.press('End');
  assert.equal(await page.locator('#film-seek').inputValue(), '38');
  await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('#film-seek').inputValue(), '37');
  await page.getByRole('button', { name: 'Replay', exact: true }).click();
  assert.equal(await page.locator('#film-seek').inputValue(), '0');
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector('#film-seek').value) > .25);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  const paused = Number(await page.locator('#film-seek').inputValue());
  await page.waitForTimeout(150);
  assert.equal(Number(await page.locator('#film-seek').inputValue()), paused);
  await page.getByRole('button', { name: '06', exact: true }).click();
  const before = await page.locator('[data-lamp="f1-south"]').evaluate(element => getComputedStyle(element).opacity);
  await page.locator('#film-seek').focus();
  await page.keyboard.press('End');
  await page.keyboard.press('ArrowLeft');
  const after = await page.locator('[data-lamp="f1-south"]').evaluate(element => getComputedStyle(element).opacity);
  assert.equal(before, '0'); assert.equal(after, '1');
  for (let index = 0; index < 9; index++) await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('#film-seek').inputValue(), '28');
  assert.equal(await page.locator('.film-resolved').evaluate(element => getComputedStyle(element).opacity), '1');
  await page.locator('.film-viewport').screenshot({ path: 'output/animation-review/resolved.png' });
  await page.getByRole('button', { name: '03', exact: true }).click();
  await page.locator('.film-seek-label span').getByText('Select the facility', { exact: true }).waitFor();
  assert.equal(await page.locator('[data-lamp="f1-south"]').evaluate(element => getComputedStyle(element).opacity), '0');
  await page.locator('.film-viewport').screenshot({ path: 'output/animation-review/reverse.png' });
  const reversed = await page.evaluate(() => document.getAnimations().map(animation => { const style = getComputedStyle(animation.effect.target); return [animation.currentTime, style.transform, style.opacity]; }));
  assert.deepEqual(reversed, sceneThree, 'Reverse seek changed animation state at the same time');
  await page.getByRole('button', { name: 'Fullscreen', exact: true }).click();
  await page.waitForFunction(() => document.fullscreenElement !== null);
  assert(await page.locator('.film-canvas').evaluate(element => { const rect = element.getBoundingClientRect(); return rect.left >= -1 && rect.top >= -1 && rect.right <= innerWidth + 1 && rect.bottom <= innerHeight + 1; }));
  await page.evaluate(() => document.exitFullscreen());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '04', exact: true }).click();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const frameSize = await page.locator('#film-scene-4 .film-panel').evaluate(panel => ({ frame: Number(panel.querySelector('.pixel-frame').getAttribute('width')), expected: panel.offsetWidth + 2 }));
  assert(Math.abs(frameSize.frame - frameSize.expected) <= 1, `Scaled preview frame measured screen pixels: ${JSON.stringify(frameSize)}`);
  await page.screenshot({ path: 'output/animation-review/mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => localStorage.length), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: 7 scenes, panel fit/isolation, scene jumps, keyboard seeking, replay, play/pause, lamp restoration, reverse-seek state equality, fullscreen fit, mobile fit, zero storage writes, no browser errors.');
} finally { await browser.close(); }
